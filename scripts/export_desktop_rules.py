#!/usr/bin/env python3
"""Export routing datasets only; never read proxy settings or credentials."""
import argparse
import hashlib
import ipaddress
import json
from pathlib import Path


def varint(data, pos):
    value = shift = 0
    while pos < len(data) and shift < 70:
        byte = data[pos]
        pos += 1
        value |= (byte & 127) << shift
        if byte < 128:
            return value, pos
        shift += 7
    raise ValueError('Invalid protobuf varint')


def fields(data):
    pos = 0
    while pos < len(data):
        key, pos = varint(data, pos)
        wire = key & 7
        if wire == 0:
            value, pos = varint(data, pos)
        elif wire == 2:
            length, pos = varint(data, pos)
            if pos + length > len(data):
                raise ValueError('Truncated protobuf field')
            value = data[pos:pos + length]
            pos += length
        else:
            raise ValueError(f'Unsupported protobuf wire type {wire}')
        yield key >> 3, value


def entries(data, country):
    matches = []
    for key, value in fields(data):
        if key != 1:
            continue
        parts = list(fields(value))
        code = next(v.decode() for k, v in parts if k == 1)
        if code.lower() == country:
            if any(k == 3 and v == 1 for k, v in parts):
                raise ValueError('Inverse GeoIP sets are unsupported')
            matches.append([dict(fields(v)) for k, v in parts if k == 2])
    if len(matches) != 1:
        raise ValueError(f'Expected one dataset for {country}')
    return matches[0]


def export(geosite_path, geoip_path, destination):
    geosite = geosite_path.read_bytes()
    geoip = geoip_path.read_bytes()
    datasets, omitted = {}, []
    for country in ('cn', 'private', 'apple', 'microsoft', 'github', 'github-copilot'):
        rows = []
        for item in entries(geosite, country):
            kind, value = item.get(1, 0), item[2].decode()
            if kind == 1:
                # Shadowrocket has no documented DOMAIN-REGEX equivalent.
                if country != 'private':
                    raise ValueError(f'Cannot safely translate {country} regex: {value}')
                omitted.append({'dataset': country, 'type': 'regex', 'value': value})
                continue
            rule_type = {0: 'DOMAIN-KEYWORD', 2: 'DOMAIN-SUFFIX', 3: 'DOMAIN'}[kind]
            if any(c in value for c in ',\r\n'):
                raise ValueError('Unsupported domain value')
            rows.append(f'{rule_type},{value}')
        datasets[f'{country}-domains.list'] = sorted(set(rows))
    # Explicit exceptions supported by GitHub's Copilot allowlist and Microsoft
    # Copilot documentation. Keep shared Microsoft authentication endpoints direct.
    copilot_extra = [
        'DOMAIN-SUFFIX,copilot.microsoft.com',
        'DOMAIN-SUFFIX,copilot.cloud.microsoft',
        'DOMAIN-SUFFIX,m365copilot.com',
        'DOMAIN-SUFFIX,default.exp-tas.com',
    ]
    datasets['github-copilot-proxy.list'] = sorted(set(
        datasets['github-domains.list'] + datasets['github-copilot-domains.list'] + copilot_extra))
    ip_rows = []
    for item in entries(geoip, 'cn'):
        address = ipaddress.ip_address(item[1])
        network = ipaddress.ip_network(f'{address}/{item.get(2, 0)}', strict=True)
        kind = 'IP-CIDR' if address.version == 4 else 'IP-CIDR6'
        ip_rows.append(f'{kind},{network}')
    datasets['cn-ip.list'] = sorted(set(ip_rows))
    destination.mkdir(parents=True, exist_ok=True)
    metadata = {'schema': 1, 'snapshot_date': '2026-10-11', 'source_format': 'v2ray routercommon protobuf',
                'inputs': {'geosite_sha256': hashlib.sha256(geosite).hexdigest(),
                           'geoip_sha256': hashlib.sha256(geoip).hexdigest()},
                'omitted': omitted, 'files': {}}
    for name, rows in datasets.items():
        content = '# Desktop routing data snapshot; generated by scripts/export_desktop_rules.py\n' + '\n'.join(rows) + '\n'
        (destination / name).write_text(content, encoding='utf-8', newline='\n')
        metadata['files'][name] = {'rules': len(rows), 'sha256': hashlib.sha256(content.encode()).hexdigest()}
    (destination / 'manifest.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({name: len(rows) for name, rows in datasets.items()}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--geosite', required=True, type=Path)
    parser.add_argument('--geoip', required=True, type=Path)
    args = parser.parse_args()
    export(args.geosite, args.geoip, Path(__file__).resolve().parents[1] / 'rules')
